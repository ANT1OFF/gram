import * as Schema from "effect/Schema";
import { Attachment } from "./domain.ts";
import { ThreadId } from "./ids.ts";

/** Drafts one thread keeps stashed; stashing past it drops the oldest. */
export const DRAFT_STASH_LIMIT = 20;

/** A stash's server-generated id. */
export const StashId = Schema.String.check(Schema.isPattern(/^[A-Za-z0-9-]{8,64}$/)).pipe(
  Schema.brand("StashId"),
);
export type StashId = typeof StashId.Type;

/** A composer draft set aside with ⌘S: its text and the attachments it had staged. */
export const DraftStash = Schema.Struct({
  id: StashId,
  threadId: ThreadId,
  text: Schema.String,
  attachments: Schema.Array(Attachment),
  createdAt: Schema.Number,
});
export type DraftStash = typeof DraftStash.Type;

export const DraftStashList = Schema.Struct({
  /** Newest first, at most `DRAFT_STASH_LIMIT`. */
  stashes: Schema.Array(DraftStash),
});
export type DraftStashList = typeof DraftStashList.Type;

export const StashListFields = { threadId: ThreadId };

export const StashAddFields = {
  /** Generated by the client, so a retried add stores the stash once. */
  id: StashId,
  threadId: ThreadId,
  text: Schema.String,
  attachments: Schema.Array(Attachment),
};

export const StashTakeFields = { threadId: ThreadId, stashId: StashId };

export const StashRemoveFields = {
  threadId: ThreadId,
  stashId: StashId,
  /** Upload paths the composer's live draft still uses, which a discard must keep. */
  keep: Schema.optionalKey(Schema.Array(Schema.String)),
};
