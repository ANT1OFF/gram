#!/usr/bin/env node
// Generates a mock kit's tokens.css from the workspace's own theme stylesheet, so mocks wear the
// product's colours, type and radii instead of a look the agent invents. Dependency-free.
//
//   node .agents/skills/mock-build/scripts/mock-tokens.mjs <tokens.config.json> [--out <file>] [--check]
//
// The config names the theme file and the selectors whose custom properties hold the light and
// dark palettes; paths in it resolve against the config's own folder. See ../SKILL.md.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The colour tokens every kit page may use; a theme must supply each, directly or through `map`. */
export const COLOR_TOKENS = [
  "surface-1",
  "surface-2",
  "surface-3",
  "surface-hover",
  "fg",
  "fg-muted",
  "fg-subtle",
  "border-subtle",
  "border-strong",
  "accent",
  "accent-hover",
  "accent-text",
  "on-accent",
  "danger",
  "success",
  "warning",
  "info",
  "danger-text",
  "success-text",
  "warning-text",
  "info-text",
  "status-needs",
  "status-working",
  "status-idle",
  "merged",
  "focus-ring",
  "selection",
];

/** Shape tokens read from the base selector when it has them; the kit falls back otherwise. */
export const BASE_TOKENS = ["radius-xs", "radius-sm", "radius-md", "radius-lg", "radius-xl"];

const FALLBACK_UI = 'ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif';
const FALLBACK_MONO = 'ui-monospace, "SF Mono", Menlo, Consolas, monospace';

/** Each rule's selectors and its custom properties, in source order; nested rules are read too. */
export function parseRules(css) {
  // Comments and statement at-rules (@import, @charset) would otherwise join the next selector.
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/@[\w-]+[^{};]*;/g, "");
  const rules = [];
  for (const match of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selectors = match[1]
      .split(",")
      .map((s) => s.replace(/\s+/g, " ").trim())
      .filter(Boolean);
    const props = new Map();
    for (const decl of match[2].matchAll(/--([\w-]+)\s*:\s*([^;]+?)\s*(?:;|$)/g)) {
      props.set(decl[1], decl[2].replace(/\s+/g, " "));
    }
    if (props.size > 0) rules.push({ selectors, props });
  }
  return rules;
}

/** The custom properties of every rule whose selector list includes `selector`, later ones winning. */
export function propsFor(rules, selector) {
  const wanted = selector.replace(/\s+/g, " ").trim();
  const props = new Map();
  for (const rule of rules) {
    if (!rule.selectors.includes(wanted)) continue;
    for (const [name, value] of rule.props) props.set(name, value);
  }
  return props;
}

/** `value` with each `var(--x)` it can resolve from `scope` replaced, to a fixed depth. */
const resolveVars = (value, scope, depth = 0) =>
  depth > 8
    ? value
    : value.replace(/var\(--([\w-]+)(?:\s*,\s*([^()]*))?\)/g, (whole, name, fallback) => {
        const found = scope.get(name);
        if (found !== undefined) return resolveVars(found, scope, depth + 1);
        return fallback === undefined ? whole : fallback.trim();
      });

const fontStack = (family, fallback) =>
  family === undefined || family === "" ? fallback : `"${family}", ${fallback}`;

const decls = (pairs, indent) => pairs.map(([n, v]) => `${indent}--${n}: ${v};`).join("\n");

/** The kit's tokens.css for `config`, given the theme stylesheet's text. Throws on a missing token. */
export function buildTokens(config, css, sourceLabel) {
  const rules = parseRules(css);
  const base = config.base === undefined ? new Map() : propsFor(rules, config.base);
  const map = config.map ?? {};
  const palette = (selector, label) => {
    const own = propsFor(rules, selector);
    if (own.size === 0)
      throw new Error(`No custom properties for the ${label} selector ${selector}`);
    const scope = new Map([...base, ...own]);
    const missing = [];
    const out = COLOR_TOKENS.map((token) => {
      const value = scope.get(map[token] ?? token);
      if (value === undefined) missing.push(map[token] ?? token);
      return [token, value === undefined ? "" : resolveVars(value, scope)];
    });
    if (missing.length > 0) {
      throw new Error(
        `The ${label} palette (${selector}) has no ${missing.map((m) => `--${m}`).join(", ")}; add them to "map" in the config`,
      );
    }
    return out;
  };
  const light = palette(config.light, "light");
  const dark = config.dark === undefined ? undefined : palette(config.dark, "dark");
  const shape = BASE_TOKENS.flatMap((token) => {
    const value = base.get(map[token] ?? token);
    return value === undefined ? [] : [[token, resolveVars(value, base)]];
  });
  const fonts = config.fonts ?? {};
  const lines = [
    `/* Generated by mock-tokens.mjs from ${sourceLabel} (light ${config.light}${
      config.dark === undefined ? "" : `, dark ${config.dark}`
    }). Do not edit: change the theme or the config, then run the script again. */`,
  ];
  if (fonts.googleFonts) {
    lines.push(
      `@import url("https://fonts.googleapis.com/css2?${fonts.googleFonts}&display=swap");`,
    );
  }
  lines.push(
    "",
    ":root {",
    `  --font-ui: ${fontStack(fonts.ui, FALLBACK_UI)};`,
    `  --font-mono: ${fontStack(fonts.mono, FALLBACK_MONO)};`,
    ...(shape.length > 0 ? [decls(shape, "  ")] : []),
    decls(light, "  "),
    "  color-scheme: light;",
    "}",
  );
  if (dark !== undefined) {
    lines.push(
      "",
      "@media (prefers-color-scheme: dark) {",
      '  :root:not([data-theme="light"]) {',
      decls(dark, "    "),
      "    color-scheme: dark;",
      "  }",
      "}",
      "",
      ':root[data-theme="dark"] {',
      decls(dark, "  "),
      "  color-scheme: dark;",
      "}",
    );
  }
  return `${lines.join("\n")}\n`;
}

const main = (argv) => {
  const args = argv.slice(2);
  const configPath = args.find((a) => !a.startsWith("--"));
  if (configPath === undefined) {
    console.error("Usage: mock-tokens.mjs <tokens.config.json> [--out <file>] [--check]");
    return 2;
  }
  const outIndex = args.indexOf("--out");
  const config = JSON.parse(readFileSync(configPath, "utf8"));
  const folder = dirname(resolve(configPath));
  const source = resolve(folder, config.source);
  if (!existsSync(source)) {
    console.error(`Theme file not found: ${source}`);
    return 1;
  }
  const out = outIndex === -1 ? resolve(folder, "tokens.css") : resolve(args[outIndex + 1]);
  const label = relative(folder, source).split("\\").join("/");
  const next = buildTokens(config, readFileSync(source, "utf8"), label);
  if (args.includes("--check")) {
    const current = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (current !== next) {
      console.error(`${relative(process.cwd(), out)} is out of date; run mock-tokens.mjs again.`);
      return 1;
    }
    console.log(`${relative(process.cwd(), out)} is up to date.`);
    return 0;
  }
  writeFileSync(out, next);
  console.log(`Wrote ${relative(process.cwd(), out)}`);
  return 0;
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
